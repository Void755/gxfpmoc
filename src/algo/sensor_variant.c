enum gxfp_sensor_variant gxfp_sensor_variant_from_chip_id(uint16_t chip_id)
{
	switch (chip_id) {
	case 0x2208:
		return GXFP_SENSOR_VARIANT_MILANG;
	case 0x2205:
		return GXFP_SENSOR_VARIANT_MILANL;
	case 0x2503:
	case 0x2504:
		return GXFP_SENSOR_VARIANT_CHICAGOHS;
	case 0x2507:
	case 0x2508:
	case 0x2510:
		return GXFP_SENSOR_VARIANT_CHICAGOT;
	default:
		return GXFP_SENSOR_VARIANT_UNKNOWN;
	}
}

const struct gxfp_sensor_variant_info *
gxfp_sensor_variant_info(enum gxfp_sensor_variant variant)
{
	size_t i;

	for (i = 0; i < sizeof(gxfp_variants) / sizeof(gxfp_variants[0]); i++) {
		if (gxfp_variants[i].variant == variant)
			return &gxfp_variants[i];
	}
	return NULL;
}

const char *gxfp_sensor_variant_name(enum gxfp_sensor_variant variant)
{
	const struct gxfp_sensor_variant_info *info =
		gxfp_sensor_variant_info(variant);

	return info ? info->name : "unknown";
}

int gxfp_sensor_variant_cfg_template(enum gxfp_sensor_variant variant,
				     const uint8_t **out_template,
				     size_t *out_len)
{
	const struct gxfp_sensor_variant_info *info =
		gxfp_sensor_variant_info(variant);

	if (!out_template || !out_len)
		return -EINVAL;
	*out_template = NULL;
	*out_len = 0;
	if (!info || !info->cfg_template)
		return -ENOTSUP;

	*out_template = info->cfg_template;
	*out_len = GXFP_SENSOR_CFG_LEN;
	return 0;
}
